#!/bin/bash
# Create the realm, export keytabs and a host krb5.conf, then run the KDC.
# Runs on every start, so keys (and keytabs) change each time.
set -euo pipefail

REALM="${REALM:-WORMHOLE.TEST}"
SERVICE_HOST="${SERVICE_HOST:-localhost}"  # the hostname clients put in the URL
SERVICE_PRINC="HTTP/${SERVICE_HOST}"
CLIENT_PRINC="${CLIENT_PRINC:-svc-tokentest}"
HOST_PORT="${HOST_PORT:-8088}"  # published port - the host krb5.conf must name it
OUT=/keytabs

echo -e "[libdefaults]\n    default_realm = ${REALM}" > /etc/krb5.conf

cat > /etc/krb5kdc/kdc.conf <<EOF
[realms]
    ${REALM} = {
        supported_enctypes = aes256-cts-hmac-sha1-96:normal aes128-cts-hmac-sha1-96:normal
    }
EOF

# `kdb5_util create` fails if a database exists (e.g. after stop/start).
rm -f /var/lib/krb5kdc/principal*
kdb5_util create -r "${REALM}" -s -W -P masterpassword  # -W: don't block on entropy

rm -f "${OUT}"/*.keytab  # ktadd appends to an existing keytab
kadmin.local -q "addprinc -randkey ${SERVICE_PRINC}"
kadmin.local -q "addprinc -randkey ${CLIENT_PRINC}"
kadmin.local -q "ktadd -k ${OUT}/service.keytab ${SERVICE_PRINC}"
kadmin.local -q "ktadd -k ${OUT}/client.keytab ${CLIENT_PRINC}"

cat > "${OUT}/krb5.conf" <<EOF
# Generated by docker/krb5/provision.sh; overwritten on every start.
[libdefaults]
    default_realm = ${REALM}
    dns_lookup_kdc = false
    dns_lookup_realm = false
    rdns = false

[realms]
    ${REALM} = {
        kdc = localhost:${HOST_PORT}
    }

[domain_realm]
    ${SERVICE_HOST} = ${REALM}
EOF
chmod 0644 "${OUT}"/*  # the container runs as root; the host user must read these

echo "==> realm ${REALM} ready: ${SERVICE_PRINC}, ${CLIENT_PRINC}; files in ${OUT}"
exec krb5kdc -n
