#!/bin/bash
# Create the realm, seed principals, export keytabs, then run the KDC.
# Runs on every start: names and paths stay the same, but keys are regenerated,
# so keytabs from a previous start stop working.
set -euo pipefail

REALM="${REALM:-WORMHOLE.TEST}"
MASTER_PASSWORD="${MASTER_PASSWORD:-masterpassword}"
# The hostname clients put in the URL. "localhost" because the test client
# reaches the service in-process and the KDC through a published port.
SERVICE_HOST="${SERVICE_HOST:-localhost}"
SERVICE_PRINC="HTTP/${SERVICE_HOST}"
CLIENT_PRINC="${CLIENT_PRINC:-svc-tokentest}"
OUT="${OUT:-/keytabs}"
# Host-side published port; the host krb5.conf must name it (clients assume 88).
HOST_PORT="${HOST_PORT:-8088}"

echo "==> provisioning realm ${REALM}"

cat > /etc/krb5.conf <<EOF
[libdefaults]
    default_realm = ${REALM}
    dns_lookup_kdc = false
    dns_lookup_realm = false
    rdns = false
    udp_preference_limit = 1

[realms]
    ${REALM} = {
        kdc = localhost
        admin_server = localhost
    }

[domain_realm]
    .${SERVICE_HOST} = ${REALM}
    ${SERVICE_HOST} = ${REALM}
EOF

cat > /etc/krb5kdc/kdc.conf <<EOF
[kdcdefaults]
    kdc_ports = 88
    kdc_tcp_ports = 88

[realms]
    ${REALM} = {
        max_life = 24h 0m 0s
        max_renewable_life = 7d 0h 0m 0s
        supported_enctypes = aes256-cts-hmac-sha1-96:normal aes128-cts-hmac-sha1-96:normal
    }
EOF

# Wipe first: `kdb5_util create` fails if the database exists, which would
# leave the container dead after `docker compose stop && start`.
rm -f /var/lib/krb5kdc/principal*

# -W uses /dev/urandom rather than blocking on entropy.
kdb5_util create -r "${REALM}" -s -W -P "${MASTER_PASSWORD}"

kadmin.local -q "addprinc -randkey ${SERVICE_PRINC}"
kadmin.local -q "addprinc -randkey ${CLIENT_PRINC}"
# A principal deliberately NOT exported to the service keytab, so a test can
# prove the configured keytab is the one actually opened.
kadmin.local -q "addprinc -randkey decoy/nowhere"

mkdir -p "${OUT}"
rm -f "${OUT}/service.keytab" "${OUT}/client.keytab" "${OUT}/decoy.keytab"
kadmin.local -q "ktadd -k ${OUT}/service.keytab ${SERVICE_PRINC}"
kadmin.local -q "ktadd -k ${OUT}/client.keytab ${CLIENT_PRINC}"
kadmin.local -q "ktadd -k ${OUT}/decoy.keytab decoy/nowhere"

# The host reads these; the container runs as root and would otherwise leave
# them unreadable to your user.
chmod 0644 "${OUT}"/*.keytab

# A krb5.conf for the host, pointing at the published port.
cat > "${OUT}/krb5.conf" <<EOF
# Generated by docker/krb5/provision.sh -- do not edit, it is overwritten on
# every container start. Point TEST.KERBEROS.krb5_config and
# AUTH.kerberos.krb5_config at this file.
[libdefaults]
    default_realm = ${REALM}
    dns_lookup_kdc = false
    dns_lookup_realm = false
    rdns = false

[realms]
    ${REALM} = {
        kdc = localhost:${HOST_PORT}
    }

[domain_realm]
    .${SERVICE_HOST} = ${REALM}
    ${SERVICE_HOST} = ${REALM}
EOF
chmod 0644 "${OUT}/krb5.conf"

echo "==> realm ${REALM} ready"
echo "    service principal : ${SERVICE_PRINC}@${REALM}"
echo "    client principal  : ${CLIENT_PRINC}@${REALM}"
echo "    keytabs + krb5.conf written to ${OUT}"
echo "    host krb5.conf points at localhost:${HOST_PORT}"

exec krb5kdc -n
